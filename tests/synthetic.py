def high_entropy(n: int = 8192, seed: int = 1234) -> bytes:
    return random.Random(seed).randbytes(n)


def build_game_tree(root: Path) -> dict[str, bytes]:
    """Create a synthetic 'game install' layout and return {relative path: bytes}."""
    files: dict[str, bytes] = {
        "Game_Data/data.unity3d": unityfs_bundle(),
        "Game_Data/sharedassets0.assets": serialized_file(version=22),
        "Game_Data/sharedassets0.assets.resS": bytes(range(256)) * 4,
        "Game_Data/level0": serialized_file(version=17, unity_version="2019.4.40f1"),
        "Game_Data/StreamingAssets/creatures/creature_a.bundle": unityfs_bundle(engine_version="2021.3.15f1"),
        "Game_Data/StreamingAssets/creatures/locked.bundle": unityfs_bundle(extra_flags=0x400),
        "Game_Data/StreamingAssets/creatures/mystery.bundle": high_entropy(),
        "Game_Data/il2cpp_data/Metadata/global-metadata.dat": il2cpp_metadata(),
        "Exports/creature_a.fbx": fbx_binary_header(),
        "Exports/creature_a.glb": glb(),
        "Exports/creature_a_albedo.png": png(),
        "Exports/creature_a_normal.dds": dds(),
        "Exports/creature_a_mask.ktx2": ktx2(),
        "Project/Assets/Creature.prefab": UNITY_PREFAB_YAML.encode(),
        "Project/Assets/Creature.prefab.meta": UNITY_META.encode(),
        "Project/notes.txt": b"plain notes\n",
        "Project/settings.json": b'{"a": 1}',
        "empty.dat": b"",
    }
    for rel, data in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
    return files


def snapshot_tree(root: Path) -> dict[str, tuple[int, int, bytes]]:
    """(size, mtime_ns, bytes) for every file, to prove a scan changed nothing."""
    out = {}
    for dirpath, _dirs, names in os.walk(root):
        for name in names:
            p = Path(dirpath) / name
            st = p.lstat()
            out[str(p.relative_to(root))] = (st.st_size, st.st_mtime_ns, p.read_bytes() if p.is_file() else b"")
    return out
