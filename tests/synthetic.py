"""Builders for synthetic test assets.

Every byte here is generated by the tests; no game data is used or committed.
Structures follow the public layouts documented in UnityPy (bundle and
SerializedFile headers), the PNG/DDS/KTX/glTF/FBX specifications, and Unity's
text YAML format. They are *structurally* valid where noted, not real assets.
"""

from __future__ import annotations

import os
import random
import struct
import zlib
from pathlib import Path


def _align(buf: bytearray, n: int = 16) -> None:
    while len(buf) % n:
        buf.append(0)


def unityfs_bundle(
    *,
    format_version: int = 8,
    player_version: str = "5.x.x",
    engine_version: str = "2021.3.15f1",
    node_name: str = "CAB-synthetic.resS",
    payload: bytes = b"synthetic payload\n" * 4,
    extra_flags: int = 0,
    size_override: int | None = None,
) -> bytes:
    """A structurally valid, uncompressed UnityFS bundle with one raw node.

    Layout (big-endian): signature, format version, player/engine strings,
    total size (i64), compressed/uncompressed block-info sizes, flags; 16-byte
    alignment for format >= 7; block info (16-byte hash, blocks, nodes); data.
    The single node is named ``*.resS`` so parsers treat it as raw resource
    data rather than a SerializedFile.
    """
    blocks_info = bytearray(16)  # uncompressed-data hash (unused)
    blocks_info += struct.pack(">i", 1)
    blocks_info += struct.pack(">IIH", len(payload), len(payload), 0)  # u_size, c_size, flags (no compression)
    blocks_info += struct.pack(">i", 1)
    blocks_info += struct.pack(">qqI", 0, len(payload), 4) + node_name.encode() + b"\x00"

    flags = 0x40 | extra_flags  # BlocksAndDirectoryInfoCombined, block-info compression = none
    header = bytearray(b"UnityFS\x00")
    header += struct.pack(">I", format_version)
    header += player_version.encode() + b"\x00" + engine_version.encode() + b"\x00"
    size_pos = len(header)
    header += struct.pack(">qIII", 0, len(blocks_info), len(blocks_info), flags)
    if format_version >= 7:
        _align(header)
    body = bytes(header) + bytes(blocks_info) + payload
    total = size_override if size_override is not None else len(body)
    body = body[:size_pos] + struct.pack(">q", total) + body[size_pos + 8:]
    return body


def legacy_bundle(signature: str = "UnityWeb") -> bytes:
    return signature.encode() + b"\x00" + struct.pack(">I", 3) + b"3.x.x\x00" + b"4.7.2f1\x00" + bytes(64)


def serialized_file(*, version: int = 22, unity_version: str = "2021.3.15f1", body_size: int = 256) -> bytes:
    """A SerializedFile header + metadata start, padded to a consistent declared size."""
    metadata = unity_version.encode() + b"\x00" + struct.pack("<i", 19) + b"\x00" * 32
    if version >= 22:
        header_len = 48
        total = header_len + len(metadata) + body_size
        data_offset = header_len + len(metadata)
        header = struct.pack(">IIII", 0, 0, version, 0) + b"\x00\x00\x00\x00"
        header += struct.pack(">IqqQ", len(metadata), total, data_offset, 0)
    else:
        header_len = 20
        total = header_len + len(metadata) + body_size
        data_offset = header_len + len(metadata)
        header = struct.pack(">IIII", len(metadata), total, version, data_offset) + b"\x00\x00\x00\x00"
    return header + metadata + b"\x00" * body_size


def png(width: int = 4, height: int = 2) -> bytes:
    """A complete, decodable RGB PNG."""
    def chunk(tag: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data))

    # One scanline per row: filter byte + width * RGB.
    raw = b"".join(b"\x00" + bytes((x * 60) % 256 for x in range(width * 3)) for _ in range(height))
    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw))
            + chunk(b"IEND", b""))


def dds(width: int = 64, height: int = 32, fourcc: bytes = b"DXT1") -> bytes:
    header = bytearray(128)
    header[0:4] = b"DDS "
    struct.pack_into("<I", header, 4, 124)
    struct.pack_into("<II", header, 12, height, width)
    struct.pack_into("<I", header, 28, 1)
    header[84:88] = fourcc
    return bytes(header) + bytes(width * height // 2)


def ktx2(width: int = 16, height: int = 16) -> bytes:
    return b"\xabKTX 20\xbb\r\n\x1a\n" + struct.pack("<IIII", 37, 1, width, height) + bytes(64)


def glb() -> bytes:
    json_chunk = b'{"asset":{"version":"2.0"}}  '  # padded to 4 bytes
    body = struct.pack("<I4s", len(json_chunk), b"JSON") + json_chunk
    return b"glTF" + struct.pack("<II", 2, 12 + len(body)) + body


def fbx_binary_header(version: int = 7400) -> bytes:
    return b"Kaydara FBX Binary  \x00\x1a\x00" + struct.pack("<I", version) + bytes(64)


def il2cpp_metadata() -> bytes:
    return b"\xaf\x1b\xb1\xfa" + struct.pack("<i", 29) + bytes(120)


